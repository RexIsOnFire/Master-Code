export const cssBackend: LanguageBackend = {
  id: 'css',
  name: 'CSS',
  maturity: 'full',
  extensions: ['.css'],
  features: defaultFeatures({
    classes: false,
    interfaces: false,
    inheritance: false,
    generics: false,
    closures: false,
    exceptions: false,
    async: false,
    modules: false,
    browser: true,
    staticTypes: false,
  }),
  lineComment: '/*',
  blockComment: { open: '/*', close: '*/' },
  indent: '  ',
  keywords: new Set(),

  packageManager: {
    id: 'cdn',
    name: 'CDN / vendored',
    installAll: null,
    installOne: null,
    manifestFile: 'assets/vendor.json',
  },

  toolchain: [],
  entry: { file: 'styles.css', symbol: '', description: 'The stylesheet the entry page links.' },

  sourceRoot: () => '',
  testRoot: () => 'tests',
  pathFor: (file) => file.path,

  mapType(type: TypeRef) {
    return type.kind === 'named' ? type.name : type.kind;
  },

  importFor(_from, to) {
    return `@import url("${to.path}");`;
  },

  emitModule(ctx: EmitContext) {
    return renderStylesheet(documentForStylesheet(ctx.file, ctx.project), ctx.file, ctx.project);
  },

  emitUi(_doc, file, project) {
    // The document passed in belongs to the stylesheet file, which usually has
    // none of its own - the rules live on the pages that link it. Resolve the
    // owners rather than rendering an empty sheet.
    return renderStylesheet(documentForStylesheet(file, project), file, project);
  },

  emitProjectFiles: () => [],
  buildPlan: (): BuildPlan => ({ steps: [], note: 'CSS needs no build step.' }),
  runPlan: () => null,
  testPlan: () => null,
  parseDiagnostics: (): Diagnostic[] => [],
};
