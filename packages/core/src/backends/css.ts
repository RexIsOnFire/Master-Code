/**
 * CSS backend.
 *
 * A stylesheet is generated from the rules a UI document declares, grouped by
 * media query so the responsive breakpoints stay readable. Rules keep the order
 * the designer put them in, because in CSS order is meaning.
 */

import type { BuildPlan, EmitContext, LanguageBackend } from './backend.ts';
import { defaultFeatures } from './backend.ts';
import { CodeWriter, kebab } from './emitter.ts';
import type { Diagnostic } from '../diagnostics.ts';
import type { Project, ProjectFile } from '../model/project.ts';
import type { UiDocument, UiStyleRule } from '../model/ui.ts';
import { walkUi } from '../model/ui.ts';
import { uiDocumentOf } from './html.ts';
import type { TypeRef } from '../types/types.ts';

export function renderStylesheet(doc: UiDocument, file: ProjectFile, project: Project): string {
  const w = new CodeWriter('  ');
  w.line(`/* Generated by Master Code for ${project.name} -> ${file.path}. */`);
  w.line('/* Rules come from the UI designer\'s style panel and per-widget classes. */');
  w.blank();

  w.line('/* <mcode:region id="user-styles"> */');
  w.line('/* </mcode:region> */');
  w.blank();

  const base = doc.rules.filter((r) => !r.media);
  const byMedia = new Map<string, UiStyleRule[]>();
  for (const r of doc.rules) {
    if (!r.media) continue;
    const list = byMedia.get(r.media);
    if (list) list.push(r);
    else byMedia.set(r.media, [r]);
  }

  if (!base.length && !byMedia.size) {
    w.line('/* No rules defined yet. */');
  }
  for (const rule of base) writeRule(w, rule);

  // Breakpoints in the document's declared order, then anything else.
  const ordered = [...byMedia.keys()].sort((a, b) => mediaRank(doc, a) - mediaRank(doc, b));
  for (const media of ordered) {
    w.blank();
    w.line(`@media ${media} {`);
    w.nest(() => {
      for (const rule of byMedia.get(media)!) writeRule(w, rule);
    });
    w.line('}');
  }
  return w.toString();
}

function writeRule(w: CodeWriter, rule: UiStyleRule): void {
  const entries = Object.entries(rule.declarations ?? {});
  if (!entries.length) return;
  w.blank();
  if (rule.comment) w.line(`/* ${rule.comment} */`);
  w.line(`${rule.selector} {`);
  w.nest(() => {
    for (const [prop, value] of entries) {
      // A custom property's leading `--` is part of its name, and the name is
      // case-sensitive. kebab() strips punctuation and lower-cases, so `--bg`
      // came out as `bg`: a declaration that parses, does nothing, and silently
      // takes every `var(--bg)` reading it down with it. Anything already
      // spelled as a custom property is passed through untouched.
      const name = prop.startsWith('--') ? prop : kebab(prop);
      w.line(`${name}: ${value};`);
    }
  });
  w.line('}');
}

function mediaRank(doc: UiDocument, media: string): number {
  const i = (doc.breakpoints ?? []).findIndex((b) => mediaQueryFor(b) === media);
  return i < 0 ? 999 : i;
}

export function mediaQueryFor(bp: { minWidth?: number; maxWidth?: number }): string {
  const parts: string[] = [];
  if (bp.minWidth) parts.push(`(min-width: ${bp.minWidth}px)`);
  if (bp.maxWidth) parts.push(`(max-width: ${bp.maxWidth}px)`);
  return parts.join(' and ') || 'all';
}

/**
 * The rules a stylesheet should contain.
 *
 * A stylesheet is named by one or more UI documents; its content is their rules
 * in file order. A sheet nobody links falls back to its own document, which is
 * how a hand-managed stylesheet keeps working.
 */
export function documentForStylesheet(file: ProjectFile, project: Project): UiDocument {
  const owners = project.files.filter((f) => {
    if (f.language !== 'html') return false;
    const doc = uiDocumentOf(f);
    return doc.stylesheets?.some((s) => s === file.id || s === file.path);
  });
  if (!owners.length) return uiDocumentOf(file);
  return {
    ...uiDocumentOf(owners[0]),
    rules: owners.flatMap((f) => uiDocumentOf(f).rules),
  };
}

/** Every class name used anywhere in the document, for the designer's picker. */
export function usedClasses(doc: UiDocument): string[] {
  const out = new Set<string>();
  walkUi(doc, (n) => n.classes?.forEach((c) => out.add(c)));
  return [...out].sort();
}

