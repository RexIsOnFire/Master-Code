/**
 * What a library offers, read from the library itself.
 *
 * Adding a library to a project records it in the manifest; this goes further
 * and reads its modules, classes and functions - parameters, defaults, types and
 * documentation - so the palette can offer them as nodes instead of leaving every
 * call to hand-written code.
 *
 * Python is read by running a small introspector under the project's own Python:
 * Pyodide in the browser demo, the local interpreter on the desktop. It needs the
 * library installed, because that is the only way to see what it really exports;
 * importing a package runs its code, so this is the same trust decision as
 * running a program that uses it, and goes through `runCommand` with the same
 * limits. The introspector itself installs nothing.
 *
 * Signatures alone are not enough. Many libraries take `**kwargs` and document
 * the real keywords instead - FalconPy declares
 * `query_devices_by_filter(self, parameters=None, **kwargs)` and lists `filter`,
 * `limit`, `sort` under "Keyword arguments". So docstrings are read too, in the
 * two conventions most of the ecosystem uses (numpydoc and Google style), and a
 * documented keyword is offered whenever the function accepts `**kwargs`.
 *
 * The result is cached in the project (`libraries/python/<name>-<version>.json`)
 * so browsing works offline. Nodes do not depend on that cache: each library node
 * carries the signature it was created from.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DiagnosticBag } from '../diagnostics.ts';
import { runCommand } from '../runtime/exec.ts';

export interface LibraryParam {
  name: string;
  /**
   * How it may be passed: `positional` only by position, `either` by position or
   * name, `keyword` only by name (including documented keywords taken through
   * `**kwargs`), `varargs` for `*args`.
   */
  kind: 'positional' | 'either' | 'keyword' | 'varargs';
  required: boolean;
  /** Annotation or documented type, as written by the library. */
  type?: string;
  /** The default's repr, for display only - an omitted argument keeps the library's own default. */
  default?: string;
  doc?: string;
  /** Known only from the documentation; the function takes it through `**kwargs`. */
  fromDoc?: boolean;
}

export interface LibraryCallable {
  /** As the library spells it. */
  name: string;
  /** Null when the signature could not be read (some compiled functions). */
  params: LibraryParam[] | null;
  /** Accepts `**kwargs` beyond what is documented. */
  extraKeywords?: boolean;
  returns?: string;
  doc?: string;
  async?: boolean;
}

export interface LibraryClass {
  name: string;
  doc?: string;
  init: LibraryCallable;
  methods: LibraryCallable[];
}

export interface LibraryModule {
  name: string;
  functions: LibraryCallable[];
  classes: LibraryClass[];
  /** Set when the module could not be imported; the rest of the package is still read. */
  error?: string;
}

export interface LibrarySurface {
  language: 'python';
  /** The package name in the manifest, which may differ from its modules' names. */
  package: string;
  version: string;
  modules: LibraryModule[];
  /** True when the per-package limit cut the listing short. */
  truncated: boolean;
}

/** Introspector file, written into the output directory for the run and removed afterwards. */
export const INTROSPECTOR_PY = '_mcode_inspect.py';
const SURFACE_JSON = '_mcode_library.json';
/** Upper bound on callables read from one package, so a vast package cannot produce an unusable listing. */
const MAX_CALLABLES = 20_000;

const PYTHON_INTROSPECTOR = String.raw`# Generated by Master Code to read what a library offers. Not part of your project.
import importlib, inspect, json, re, sys
import importlib.metadata as metadata

DIST, OUTPUT, LIMIT = sys.argv[1], sys.argv[2], int(sys.argv[3])
count = [0]
truncated = [False]

def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()

def top_level_modules(dist):
    wanted = norm(dist)
    found = sorted({m for m, ds in metadata.packages_distributions().items() if any(norm(d) == wanted for d in ds)})
    return [m for m in found if not m.startswith("_")] or [wanted.replace("-", "_")]

HEADERS = {"parameters", "keyword arguments", "keyword args", "other parameters", "args", "arguments", "kwargs"}
STOP = {"returns", "return", "yields", "raises", "examples", "example", "see also", "notes", "note", "references",
        "attributes", "methods", "warns", "warnings", "todo", "http method", "swagger url"}

def first_paragraph(text, limit=300):
    para = text.strip().split("\n\n")[0].replace("\n", " ").strip()
    return para[:limit]

def parse_doc(doc):
    """Documented parameters, numpydoc or Google style: name -> {type, doc}."""
    found = {}
    lines = (doc or "").splitlines()
    i = 0
    while i < len(lines):
        raw = lines[i]
        title = raw.strip().rstrip(":").lower()
        numpy = i + 1 < len(lines) and re.match(r"^\s*-{3,}\s*$", lines[i + 1] or "")
        google = raw.strip().endswith(":") and title in HEADERS
        if title in HEADERS and (numpy or google):
            base = len(raw) - len(raw.lstrip())
            i += 2 if numpy else 1
            entry_indent = None
            current = None
            while i < len(lines):
                line = lines[i]
                text = line.strip()
                indent = len(line) - len(line.lstrip())
                if text and numpy and i + 1 < len(lines) and re.match(r"^\s*-{3,}\s*$", lines[i + 1]) and indent <= base:
                    break
                if text and google and indent <= base:
                    break
                # "Returns: dict ...", "HTTP Method: GET" - a new section, not a parameter.
                if text.split(":")[0].strip().lower() in STOP and indent <= base:
                    break
                if not text:
                    i += 1
                    continue
                if entry_indent is None:
                    entry_indent = indent
                if indent == entry_indent:
                    m = re.match(r"^\*{0,2}([A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*\*{0,2}[A-Za-z_][A-Za-z0-9_]*)*)\s*(?:\(([^)]*)\))?\s*(?::\s*(.*))?$", text)
                    # Parameter names are lower case in practice; a capitalised word is prose.
                    if m and not m.group(1)[0].isupper():
                        names = [n.strip().lstrip("*") for n in m.group(1).split(",")]
                        kind = (m.group(2) or "").strip()
                        rest = (m.group(3) or "").strip()
                        typ, desc = (kind, rest) if google or kind else (rest, "")
                        current = []
                        for n in names:
                            found[n] = {"type": typ or None, "doc": desc}
                            current.append(n)
                    else:
                        current = None
                elif current:
                    for n in current:
                        if not found[n]["doc"]:
                            found[n]["doc"] = text
                i += 1
            continue
        i += 1
    for item in found.values():
        item["doc"] = (item["doc"] or "")[:200]
    return found

KINDS = {
    inspect.Parameter.POSITIONAL_ONLY: "positional",
    inspect.Parameter.POSITIONAL_OR_KEYWORD: "either",
    inspect.Parameter.KEYWORD_ONLY: "keyword",
    inspect.Parameter.VAR_POSITIONAL: "varargs",
}

def annotation_text(a):
    if a is inspect.Parameter.empty or a is inspect.Signature.empty:
        return None
    return a if isinstance(a, str) else inspect.formatannotation(a)

def short_repr(value):
    try:
        text = repr(value)
    except Exception:
        return None
    return text if len(text) <= 40 else text[:37] + "..."

def describe(fn, name, skip_first, doc_source=None):
    count[0] += 1
    doc = inspect.getdoc(doc_source if doc_source is not None else fn) or ""
    documented = parse_doc(doc)
    try:
        sig = inspect.signature(fn)
    except (TypeError, ValueError):
        sig = None
    params = None
    extra = False
    returns = None
    if sig is not None:
        params = []
        values = list(sig.parameters.values())
        if skip_first and values and values[0].kind in (inspect.Parameter.POSITIONAL_ONLY, inspect.Parameter.POSITIONAL_OR_KEYWORD):
            values = values[1:]
        for p in values:
            if p.kind == inspect.Parameter.VAR_KEYWORD:
                extra = True
                continue
            info = documented.get(p.name, {})
            entry = {
                "name": p.name,
                "kind": KINDS[p.kind],
                "required": p.default is inspect.Parameter.empty and p.kind != inspect.Parameter.VAR_POSITIONAL,
            }
            typ = annotation_text(p.annotation) or info.get("type")
            if typ:
                entry["type"] = typ
            if p.default is not inspect.Parameter.empty:
                shown = short_repr(p.default)
                if shown is not None:
                    entry["default"] = shown
            if info.get("doc"):
                entry["doc"] = info["doc"]
            params.append(entry)
        if extra:
            known = {p["name"] for p in params}
            for pname, info in documented.items():
                if pname in known or pname in ("args", "kwargs"):
                    continue
                entry = {"name": pname, "kind": "keyword", "required": False, "fromDoc": True}
                if info.get("type"):
                    entry["type"] = info["type"]
                if info.get("doc"):
                    entry["doc"] = info["doc"]
                params.append(entry)
            extra = True
        returns = annotation_text(sig.return_annotation)
    out = {"name": name, "params": params}
    if extra:
        out["extraKeywords"] = True
    if returns:
        out["returns"] = returns
    summary = first_paragraph(doc)
    if summary:
        out["doc"] = summary
    if inspect.iscoroutinefunction(fn):
        out["async"] = True
    return out

def defined_in(obj, package):
    owner = getattr(obj, "__module__", None) or ""
    return owner == package or owner.startswith(package + ".")

def describe_class(cls, name):
    init_doc = cls.__init__ if cls.__init__ is not object.__init__ and inspect.getdoc(cls.__init__) else cls
    entry = {"name": name, "init": describe(cls, name, False, init_doc), "methods": []}
    doc = first_paragraph(inspect.getdoc(cls) or "")
    if doc:
        entry["doc"] = doc
    for mname in sorted(dir(cls)):
        if mname.startswith("_"):
            continue
        if count[0] >= LIMIT:
            truncated[0] = True
            break
        try:
            raw = inspect.getattr_static(cls, mname)
            attr = getattr(cls, mname)
        except Exception:
            continue
        if isinstance(raw, property) or not callable(attr) or inspect.isclass(attr):
            continue
        func = getattr(attr, "__func__", attr)
        real = getattr(func, "__name__", mname)
        # An alias of another public method (FalconPy's CamelCase names) is listed once, under its real name.
        if real != mname and not real.startswith("_") and hasattr(cls, real):
            continue
        plain = inspect.isfunction(raw)
        entry["methods"].append(describe(attr, mname, plain))
    return entry

def describe_module(modname, package):
    try:
        mod = importlib.import_module(modname)
    except BaseException as e:
        return {"name": modname, "functions": [], "classes": [], "error": f"{type(e).__name__}: {e}"[:300]}
    names = getattr(mod, "__all__", None)
    if not isinstance(names, (list, tuple)):
        names = [n for n in dir(mod) if not n.startswith("_")]
    functions, classes = [], []
    for name in sorted(set(names)):
        if count[0] >= LIMIT:
            truncated[0] = True
            break
        try:
            obj = getattr(mod, name)
        except Exception:
            continue
        if inspect.ismodule(obj) or not defined_in(obj, package):
            continue
        try:
            if inspect.isclass(obj):
                classes.append(describe_class(obj, name))
            elif callable(obj):
                functions.append(describe(obj, name, False))
        except Exception:
            continue
    return {"name": modname, "functions": functions, "classes": classes}

try:
    version = metadata.version(DIST)
except metadata.PackageNotFoundError:
    with open(OUTPUT, "w", encoding="utf-8") as out:
        json.dump({"error": "not-installed"}, out)
    sys.exit(3)

modules = [describe_module(m, m) for m in top_level_modules(DIST)]
with open(OUTPUT, "w", encoding="utf-8") as out:
    json.dump({"language": "python", "package": DIST, "version": version, "modules": modules, "truncated": truncated[0]}, out, ensure_ascii=False)
`;

export interface InspectOptions {
  /** Package name as recorded in the manifest. */
  name: string;
  /** Version recorded in the manifest; `*` or empty when unpinned. */
  version?: string;
  /** Where the project's generated program runs; the introspector runs there too. */
  out: string;
  /** Project directory; the result is cached under `libraries/python/`. */
  root: string;
  /** Ignore a cached result and read the library again. */
  refresh?: boolean;
  onOutput?(chunk: string, stream: 'stdout' | 'stderr'): void;
}

export interface InspectResult {
  surface?: LibrarySurface;
  cached: boolean;
  diagnostics: DiagnosticBag;
}

export function surfaceCachePath(root: string, name: string, version: string): string {
  const safe = `${name}-${version}`.replace(/[^A-Za-z0-9._-]/g, '_');
  return join(root, 'libraries', 'python', `${safe}.json`);
}

/** Reads a Python package's modules, classes and functions. */
export async function inspectPythonLibrary(options: InspectOptions): Promise<InspectResult> {
  const diagnostics = new DiagnosticBag();
  const pinned = options.version && options.version !== '*' ? options.version : '';
  if (pinned && !options.refresh) {
    const cached = surfaceCachePath(options.root, options.name, pinned);
    if (existsSync(cached)) {
      try {
        return { surface: JSON.parse(readFileSync(cached, 'utf8')) as LibrarySurface, cached: true, diagnostics };
      } catch {
        // A damaged cache is read again below.
      }
    }
  }

  mkdirSync(options.out, { recursive: true });
  const script = join(options.out, INTROSPECTOR_PY);
  const output = join(options.out, SURFACE_JSON);
  writeFileSync(script, PYTHON_INTROSPECTOR, 'utf8');
  try {
    const run = await runCommand({
      command: 'python',
      args: [INTROSPECTOR_PY, options.name, SURFACE_JSON, String(MAX_CALLABLES)],
      cwd: options.out,
      env: {
        PYTHONDONTWRITEBYTECODE: '1',
        PYTHONUTF8: '1',
        // Read by the browser demo's Python, which installs this before the run;
        // a local Python ignores it and uses what is already installed.
        MASTERCODE_INSTALL: pinned ? `${options.name}==${pinned}` : options.name,
      },
      timeoutMs: 300_000,
      maxOutputBytes: 1_000_000,
      onOutput: options.onOutput,
    });
    if (run.startError) {
      diagnostics.error('dependency', 'library/no-python', run.startError, { hint: 'Run `mcode doctor` to see which toolchains are available.' });
      return { cached: false, diagnostics };
    }
    let parsed: (LibrarySurface & { error?: string }) | undefined;
    try {
      parsed = JSON.parse(readFileSync(output, 'utf8')) as LibrarySurface & { error?: string };
    } catch {
      parsed = undefined;
    }
    if (parsed?.error === 'not-installed') {
      diagnostics.error('dependency', 'library/not-installed', `${options.name} is not installed, so there is nothing to read its functions from.`, {
        hint: `Install it first: python -m pip install ${pinned ? `${options.name}==${pinned}` : options.name}`,
      });
      return { cached: false, diagnostics };
    }
    if (!parsed || run.code !== 0) {
      diagnostics.error('dependency', 'library/inspect-failed', `Could not read ${options.name}'s functions.`, {
        raw: `${run.stderr || run.stdout}`.trim().split('\n').slice(-8).join('\n') || undefined,
      });
      return { cached: false, diagnostics };
    }
    for (const module of parsed.modules) {
      if (module.error) diagnostics.warn('dependency', 'library/module-failed', `${module.name} could not be imported: ${module.error}`);
    }
    if (parsed.truncated) {
      diagnostics.info('dependency', 'library/truncated', `${options.name} is large; only the first ${MAX_CALLABLES} functions were read.`);
    }
    const cache = surfaceCachePath(options.root, options.name, parsed.version);
    mkdirSync(join(options.root, 'libraries', 'python'), { recursive: true });
    writeFileSync(cache, `${JSON.stringify(parsed)}\n`, 'utf8');
    return { surface: parsed, cached: false, diagnostics };
  } finally {
    rmSync(script, { force: true });
    rmSync(output, { force: true });
  }
}
