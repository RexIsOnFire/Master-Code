  '              version="1.0.0", setup=None, derive=None, ingest=None,',
  '              hunt=None):',
  '    # A connector manifest. Installing one publishes its commands; no engine',
  '    # change.',
  '    #',
  '    # setup is what THIS vendor needs before it can be reached, and no two',
  '    # agree: CrowdStrike wants a cloud region, Sentinel a tenant and a',
  '    # workspace, Splunk a host and a port. Asking every connector for a',
