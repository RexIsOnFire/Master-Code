  '        "name": name, "label": label, "kind": kind, "required": required,',
  '        "default": default, "options": options or [], "help": help,',
  '        "placeholder": placeholder,',
  '    }',
  '',
  '',
  'def connector(cid, name, vendor, category, auth, base_url, allowlist, commands,',
