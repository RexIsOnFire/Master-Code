  '    """',
  '    One command definition.',
  '',
  '    Structured JSON in, structured JSON out. The output_schema is what the',
  '    playbook validator type-checks the next step against, so a command whose',
  '    schema lies fails at publish rather than at 03:00.',
  '    """',
  '    definition = {',
  '        "key": key,',
  '        "name": name,',
  '        "category": category,',
  '        "kind": "http",',
  '        "input_schema": {',
  '            "type": "object",',
  '            "required": list(inputs.keys()) if required is None else required,',
  '            "properties": inputs,',
  '            "additionalProperties": False,',
  '        },',
  '        "output_schema": {"type": "object", "properties": outputs},',
  '        "implementation": {',
  '            "method": method,',
  '            "url": url,',
  '            "extract": extract or {},',
  '            "success_codes": success or [200, 201, 202, 204],',
  '        },',
