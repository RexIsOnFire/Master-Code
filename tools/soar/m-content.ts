/**
 * The prebuilt command library.
 *
 * Every connector is a manifest. There is no CrowdStrike module, no Defender
 * module and no vendor branch anywhere in the engine - if there were, a SOC
 * could not add its own vendor without waiting for a release.
 *
 * The shape of the library follows what a SOC actually needs and where the
 * capability actually lives:
 *
 *   SIEM      is where alerts and hunting queries come from. It observes.
 *   EDR       is where containment lives - isolate, kill, quarantine, block.
 *   Identity  is where account response lives - disable, revoke, reset.
 *   Email     is where phishing response lives - search, purge, block sender.
 *   Network   is where blocking at the perimeter lives.
 *   ITSM      is where the humans are told.
 *
 * Commands that change something are marked `effect: mutating`, carry a real
 * `risk_level`, and - where one exists - name the command that undoes them.
 * That last field is what lets a playbook declare a compensation rather than
 * the platform inventing a rollback.
 */

