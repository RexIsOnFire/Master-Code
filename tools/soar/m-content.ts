/**
 * The Python helper every pack uses, emitted once into each catalogue file.
 *
 * Keeping it as generated source rather than as a platform import means a pack
 * is readable on its own: someone reviewing catalog_edr.py sees exactly what a
 * command definition becomes.
 */
