/**
 * Simulation and reporting.
 *
 * Both were named by a caller before they existed: `playbook_simulate` calls
 * `run_simulation`, and the reports endpoints call `build_report` and
 * `export_report`. Simulation matters more than it looks - `publish()` refuses a
 * version with no passing simulation, so until this existed nothing could be
 * published at all.
 */

