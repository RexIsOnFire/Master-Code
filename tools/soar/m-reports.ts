        '    "response_actions": (',
        '        "SELECT at, action, coalesce(target_label, target_id) AS target, "',
        '        "coalesce(actor_label, actor_id) AS actor, on_behalf_of_id AS approver, "',
        '        "result FROM audit_event WHERE org_id = %s "',
        '        "AND action LIKE \'response.%%\' "',
        '        "AND at > now() - (%s || \' days\')::interval ORDER BY at DESC"),',
        '    "automation_metrics": (',
        '        "SELECT p.name AS playbook, count(*) AS runs, "',
        '        "count(*) FILTER (WHERE e.status = \'succeeded\') AS succeeded, "',
        '        "count(*) FILTER (WHERE e.status = \'failed\') AS failed, "',
        '        "percentile_disc(0.5) WITHIN GROUP (ORDER BY e.duration_ms) AS median_ms "',
        '        "FROM execution e JOIN playbook p ON p.id = e.playbook_id "',
        '        "WHERE e.org_id = %s AND e.started_at > now() - (%s || \' days\')::interval "',
