        '    "analyst_activity": (',
        '        "SELECT coalesce(actor_label, actor_id) AS analyst, "',
        '        "count(DISTINCT target_id) FILTER (WHERE target_kind = \'incident\') "',
        '        "  AS incidents_touched, "',
        '        "count(*) FILTER (WHERE action = \'approval.decided\') AS approvals, "',
        '        "count(*) FILTER (WHERE action = \'incident.note\') AS notes "',
        '        "FROM audit_event WHERE org_id = %s AND actor_kind = \'user\' "',
        '        "AND at > now() - (%s || \' days\')::interval "',
        '        "GROUP BY analyst ORDER BY incidents_touched DESC"),',
