const panel = (id: string, classes: string[], children: UiNode[]): UiNode => ({
  id,
  kind: 'panel',
  classes,
  children,
});

const label = (id: string, text: string, classes: string[] = [], name?: string): UiNode => ({
  id,
  kind: 'label',
  text,
  classes,
  name,
});

const button = (id: string, text: string, handler: string, classes: string[] = []): UiNode => ({
  id,
  kind: 'button',
  name: id.replace(/-([a-z])/g, (_, c) => c.toUpperCase()),
  text,
  classes,
  attrs: { type: 'button' },
  events: [{ event: 'click', handler }],
});

