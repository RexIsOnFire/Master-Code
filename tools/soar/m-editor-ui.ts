  // The editor owns playbook.html outright. It used to overwrite a shell page
  // created elsewhere, which meant two definitions of the same screen sat in the
  // source and only one of them was ever rendered.
  addFile(ctx.project, {
    path: 'playbook.html',
    language: 'html',
    role: 'source',
    options: {
      ui: editorDoc(web.style.id, [
        web.apiClient.id,
        modelFile.id,
        canvasFile.id,
        inspector.file.id,
        editor.file.id,
      ]),
    },
  });
