/**
 * The editor's inspector, its entry point, and the page it lives on.
 *
 * The inspector is where the "no-code" claim is either true or not. It builds a
 * typed form from the command's own `input_schema` - the same object the worker
 * validates against - so an analyst configuring "Isolate Host" fills in the
 * fields the vendor API actually takes, with the right types, without seeing
 * JSON. Nothing in the form is hand-written per command.
 */

