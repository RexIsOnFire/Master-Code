/**
 * The playbook node editor: the palette the server computes, and the canvas the
 * analyst actually draws on.
 *
 * Two properties are worth stating up front, because they are what stop this
 * being a diagram tool.
 *
 * 1. The palette is computed from the real command registry, so a node the
 *    analyst can drag is a command that exists, is published, and that THIS
 *    principal is permitted to run. You cannot draw a playbook the engine will
 *    refuse for a reason the editor could have known.
 *
 * 2. The canvas serialises to exactly the `definition` shape playbooks/engine.py
 *    executes. There is no editor format and no conversion step, so an editor
 *    that drifts from the engine is not possible.
 */

