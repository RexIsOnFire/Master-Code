        'MAX_BODY = 2 * 1024 * 1024',
        '',
        'async def read_body(receive):',
        '    chunks, size = [], 0',
        '    while True:',
        '        message = await receive()',
        '        chunk = message.get("body", b"")',
        '        size += len(chunk)',
        '        if size > MAX_BODY:',
        '            raise ValueError("request body exceeds %d bytes" % MAX_BODY)',
