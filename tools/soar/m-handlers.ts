        '',
        '    woken = db.query(',
        '        "UPDATE execution_step SET status = \'succeeded\', "',
        '        "output = \'{\\"branch\\": \\"next\\"}\'::jsonb "',
        '        "WHERE org_id = %s AND node_kind = \'delay\' AND status = \'pending\' "',
        '        "AND finished_at <= now() RETURNING execution_id",',
        '        [org_id], org_id,',
        '    )',
        '    for row in woken:',
        '        counts["woken"] += 1',
        '        advance(db, org_id, row["execution_id"])',
        '',
        '    counts["reaped"] += reap_lost_workers(db, org_id, 120)',
        '',
        '    stalled = db.query(',
        '        "SELECT id FROM execution WHERE org_id = %s AND status = \'running\' "',
        '        "AND NOT EXISTS (SELECT 1 FROM execution_step s "',
        '        "  WHERE s.execution_id = execution.id "',
        '        "  AND s.status IN (\'queued\', \'running\', \'waiting_approval\', \'pending\')) "',
