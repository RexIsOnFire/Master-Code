    fnWithBody(g, {
      name: 'purge_org_data',
      params: [
        { name: 'db', type: 'Any' },
        { name: 'org_id', type: 'string' },
      ],
      returns: 'Map<string, i64>',
      doc: [
        'Remove every row belonging to one organisation, children first.',
        '',
        'The order is computed from the foreign keys that exist right now, not',
        'written down here. Forty-four tables carry org_id and most have no key',
        'back to organisation, so a hand-kept list would be one migration away',
        'from leaving a customer\'s alerts on disk with nothing pointing at them.',
        '',
        'Tables are sorted so that anything referencing another table is emptied',
        'before the table it references. A cycle - none exist today - falls back to',
        'the order it was found in, and the delete would fail loudly rather than',
        'half-finish quietly.',
      ].join('\n'),
      implName: 'delete_org_rows',
      code: [
        '# Every table that scopes rows by organisation.',
        'scoped = [row["table_name"] for row in db.query(',
        '    "SELECT table_name FROM information_schema.columns "',
        '    "WHERE column_name = \'org_id\' AND table_schema = \'public\' "',
        '    "ORDER BY table_name", [], "")]',
        'scoped = [name for name in scoped if name != "organisation"]',
        '',
        '# Who points at whom, among those tables.',
        'edges = db.query(',
        '    "SELECT tc.table_name AS child, ccu.table_name AS parent "',
        '    "FROM information_schema.table_constraints tc "',
        '    "JOIN information_schema.constraint_column_usage ccu "',
        '    "  ON ccu.constraint_name = tc.constraint_name "',
        '    "WHERE tc.constraint_type = \'FOREIGN KEY\' "',
        '    "  AND tc.table_schema = \'public\'", [], "")',
        '',
        'depends = {name: set() for name in scoped}',
        'for edge in edges:',
        '    child, parent = edge["child"], edge["parent"]',
        '    if child in depends and parent in depends and child != parent:',
        '        depends[child].add(parent)',
        '',
        '# Children first: a table is only safe to empty once everything that',
        '# references it is already empty.',
        'order = []',
        'remaining = dict(depends)',
        'while remaining:',
        '    free = [name for name, parents in remaining.items()',
        '            if not (parents & set(remaining))]',
        '    if not free:',
        '        # A cycle. Take the rest in name order and let the database',
        '        # refuse if that is genuinely impossible, rather than guessing.',
        '        order.extend(sorted(remaining))',
        '        break',
        '    referenced_by = {}',
        '    for name, parents in remaining.items():',
        '        for parent in parents:',
        '            referenced_by[parent] = referenced_by.get(parent, 0) + 1',
        '    # Emptiest leaves first, which keeps the order stable run to run.',
        '    step = sorted(free, key=lambda n: (referenced_by.get(n, 0), n))',
        '    order.extend(step)',
        '    for name in step:',
        '        remaining.pop(name, None)',
        '',
        '# The provider keeps its own people; a client organisation has none, but',
        '# being explicit costs nothing and an account is not a detection.',
        '# Insert-only by policy: the app role has no DELETE on these, and that',
        '# is the point. A deletion that could also erase the record of itself',
        '# is not an audit trail.',
        'immutable = {"audit_event"}',
        '',
        'removed = {}',
        'retained = {}',
        'for table in order:',
        '    if table in immutable:',
        '        rows = db.query("SELECT count(*) AS n FROM " + table +',
        '                        " WHERE org_id = %s", [org_id], org_id)',
        '        if rows and rows[0]["n"]:',
        '            retained[table] = rows[0]["n"]',
        '        continue',
        '    count = db.execute("DELETE FROM " + table + " WHERE org_id = %s",',
        '                       [org_id], org_id)',
        '    if count:',
        '        removed[table] = count',
        '',
        'db.execute("DELETE FROM organisation WHERE id = %s", [org_id], org_id)',
        'removed["organisation"] = 1',
        'if retained:',
        '    removed["_retained"] = retained',
        'return removed',
      ].join('\n'),
    });

