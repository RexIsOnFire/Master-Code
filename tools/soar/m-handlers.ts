/**
 * The handler layer, and the ASGI adapter that feeds it.
 *
 * `route_table()` has always declared 81 endpoints and `dispatch_request` has
 * always looked them up in `context["handlers"]`. This is the dictionary.
 *
 * Every handler has the same shape - `(principal, params, request) -> dict` -
 * and every one of them calls a service method that checks the permission again
 * at the point of effect. The route table's permission is a first gate and a
 * piece of documentation; it is not the security model, and a handler that
 * relied on it would still be wrong.
 */

