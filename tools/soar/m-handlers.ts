        '        "content-type": content_type,',
        '        "x-content-type-options": "nosniff",',
        '        "cache-control": "no-store",',
        '    }, payload)',
        '',
        'async def app(scope, receive, send):',
        '    if scope["type"] != "http":',
        '        return',
        '',
        '    headers = {k.decode("latin-1").lower(): v.decode("latin-1")',
        '               for k, v in scope.get("headers", [])}',
        '    path = scope["path"]',
        '    method = scope["method"]',
