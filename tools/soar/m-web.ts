const panel = (id: string, classes: string[], children: UiNode[]): UiNode => ({
  id,
  kind: 'panel',
  classes,
  children,
});

const label = (id: string, text: string, classes: string[] = [], name?: string): UiNode => ({
  id,
  kind: 'label',
  text,
  classes,
  name,
});

const navItem = (
  id: string,
  text: string,
  key: string,
  active = false,
  permission?: string,
): UiNode => ({
  id,
  kind: 'link',
  text,
  classes: active ? ['nav-item', 'is-active'] : ['nav-item'],
  attrs: {
    href: '#' + id.replace('nav-', ''),
    'data-view': id.replace('nav-', ''),
    'data-key': key,
    // Rendered hidden and revealed from the session's permissions. The server
    // checks again on every request; this stops the rail being a list of
    // fifteen screens of which an analyst can open four.
    ...(permission ? { 'data-permission': permission, hidden: 'hidden' } : {}),
  },
  events: [{ event: 'click', handler: 'onNavigate' }],
});

