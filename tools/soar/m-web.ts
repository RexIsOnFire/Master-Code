/**
 * The analyst workspace: UI documents, the stylesheet, and the behaviour graphs.
 *
 * Cyberpunk, but a working one. The brief was a dark SOC interface with high
 * information density - so the theme spends its contrast on data and its accent
 * colour on state, and nothing here is a rounded pastel card. Light mode is a
 * real mode rather than an inversion: a SOC has windows, and a daylit desk needs
 * a paper ground, not a washed-out dark theme.
 *
 * Every screen is backed by a real endpoint from api/routes.py. There are no
 * mock screens.
 */

